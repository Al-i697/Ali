#!/usr/bin/env python3
"""Build src/logos.js from the three logo files in assets/logos/ (transparent PNG): qms.png (Quality Management System),
   vision2040.png (Oman Vision 2040), emblem.png (the Ministry of Education logo, current name «وزارة التعليم», emblem + name).
   To change a logo (e.g. the current Ministry of Education logo), replace the file and run:
       python3 tools/make_logos.py && python3 tools/fork_sci.py && python3 tools/build.py
   MOE_NAME is only used for alt text (the logo picture already carries the ministry name)."""
import base64, os
from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(HERE, "assets", "logos")
files = [("LOGO_QMS", "qms", "qms.png"), ("LOGO_V2040", "v2040", "vision2040.png"), ("LOGO_EMBLEM", "emblem", "emblem.png")]
consts, dims = [], {}
for const, key, name in files:
    p = os.path.join(A, name)
    consts.append(f'const {const} = "data:image/png;base64,{base64.b64encode(open(p, "rb").read()).decode()}";')
    im = Image.open(p); dims[key] = [im.width, im.height]
out = ("/* generated by tools/make_logos.py from assets/logos/*.png; do not edit by hand */\n" + "\n".join(consts) + "\n"
       + "const LOGO_DIM = " + str(dims).replace("'", '"') + ";\n"
       + 'const MOE_NAME = ["سلطنة عُمان", "وزارة التعليم"];\n')
open(os.path.join(HERE, "src", "logos.js"), "w", encoding="utf-8").write(out)
print("src/logos.js written:", len(out), "bytes", dims)
