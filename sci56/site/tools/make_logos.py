#!/usr/bin/env python3
"""Build src/logos.js from the three logo files in assets/logos/ (the Ministry of Education template's header):
   qms.jpg (Quality Management System), vision2040.jpg (Oman Vision 2040), emblem.jpg (the national emblem).
   To change a logo (e.g. the current Ministry of Education logo), replace the file and run:
       python3 tools/make_logos.py && python3 tools/fork_sci.py && python3 tools/build.py
   The ministry name next to the emblem is live text (MOE_NAME), not part of the picture."""
import base64, os
from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(HERE, "assets", "logos")
files = [("LOGO_QMS", "qms", "qms.jpg"), ("LOGO_V2040", "v2040", "vision2040.jpg"), ("LOGO_EMBLEM", "emblem", "emblem.jpg")]
consts, dims = [], {}
for const, key, name in files:
    p = os.path.join(A, name)
    consts.append(f'const {const} = "data:image/jpeg;base64,{base64.b64encode(open(p, "rb").read()).decode()}";')
    im = Image.open(p); dims[key] = [im.width, im.height]
out = ("/* generated by tools/make_logos.py from assets/logos/*.jpg; do not edit by hand */\n" + "\n".join(consts) + "\n"
       + "const LOGO_DIM = " + str(dims).replace("'", '"') + ";\n"
       + 'const MOE_NAME = ["سلطنة عُمان", "وزارة التعليم"];\n')
open(os.path.join(HERE, "src", "logos.js"), "w", encoding="utf-8").write(out)
print("src/logos.js written:", len(out), "bytes", dims)
