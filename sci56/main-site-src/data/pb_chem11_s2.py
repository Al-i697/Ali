# Per-period bookends for chemistry 11, semester 2.
# Each 40-minute period gets its own opener (prior-learning question + warm-up) and closer (assessment).
# Period 1 opens with the lesson's own warm-up row; the last period closes with the lesson's exit ticket.
# Format: PB[key] = {cuts: first existing-row index of periods 2..N, mins: new minutes for every existing row,
#                    open: [opener of period 2..N], close: [closer of period 1..N-1]}
# Every period must sum to exactly 40 minutes (build.py checks it).
def R(phase, strat, mins, teacher, student, tool, q, ans, crit):
    return [phase, strat, mins, [], teacher, student, {"tool": tool, "q": q, "ans": ans, "crit": crit}]

def OPEN(mins, teacher, student, q, ans, crit, tool="سؤال شفهي", strat="الأسئلة السابرة"):
    return R("تعلم قبلي وتمهيد", strat, mins, teacher, student, tool, q, ans, crit)

def CLOSE(mins, teacher, student, q, ans, crit, tool="بطاقة الخروج"):
    return R("تقويم ختامي للحصة", "بطاقة الخروج", mins, teacher, student, tool, q, ans, crit)

