def R(phase, strat, mins, teacher, student, tool, q, ans, crit):
    return [phase, strat, mins, [], teacher, student, {"tool": tool, "q": q, "ans": ans, "crit": crit}]

def OPEN(mins, teacher, student, q, ans, crit, tool="سؤال شفهي", strat="الأسئلة السابرة"):
    return R("تعلم قبلي وتمهيد", strat, mins, teacher, student, tool, q, ans, crit)

def CLOSE(mins, teacher, student, q, ans, crit, tool="بطاقة الخروج"):
    return R("تقويم ختامي للحصة", "بطاقة الخروج", mins, teacher, student, tool, q, ans, crit)

