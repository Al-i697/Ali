"""Pack the cut stickers (art-src/stickers/cut/*.png) into ../stickers_assets.js as WebP data URIs.   python3 pack_stickers.py"""
import os, io, base64, json
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); CUT = os.path.join(HERE, '..', 'art-src', 'stickers', 'cut')
SKIP = {'n_mol', 's_cell'}
LIM = lambda n: 300 if n.startswith('pr_') else 280   # longest side in px
img, wh, tot = {}, {}, 0
for f in sorted(os.listdir(CUT)):
    n = f[:-4]
    if not f.endswith('.png') or n in SKIP: continue
    im = Image.open(os.path.join(CUT, f)).convert('RGBA'); im.thumbnail((LIM(n), LIM(n)), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=80, method=6); data = b.getvalue(); tot += len(data)
    img[n] = 'data:image/webp;base64,' + base64.b64encode(data).decode(); wh[n] = list(im.size)
open(os.path.join(HERE, '..', 'stickers_assets.js'), 'w').write(
    '/* generated by tools/pack_stickers.py from the sticker sheets in art-src/stickers */\nvar STK_IMG=' + json.dumps(img, separators=(',', ':')) + ';\nvar STK_WH=' + json.dumps(wh, separators=(',', ':')) + ';\n')
print(len(img), 'stickers', tot // 1024, 'KB')
